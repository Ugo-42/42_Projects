const SOLID_WALL_ROWS: string[] = [
	'11111111111111111',
	'10000000000000001',
	'10101010101010101',
	'10000000000000001',
	'10101010101010101',
	'10000000000000001',
	'10101010101010101',
	'10000000000000001',
	'10101010101010101',
	'10000000000000001',
	'11111111111111111',
];

export function isSolidWallAt(col: number, row: number): boolean {
	const matrixRow = row + 1;
	const matrixCol = col + 1;
	const line = SOLID_WALL_ROWS[matrixRow];
	return line ? line[matrixCol] === '1' : false;
}
